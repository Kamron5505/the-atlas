// Generates the English agent catalog page from packages/cli/agents.conf
// (+ agents.en.json translations). Run: node apps/site/scripts/gen-agents.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../../../", import.meta.url);
const conf = readFileSync(new URL("packages/cli/agents.conf", root), "utf8");
const en = JSON.parse(readFileSync(new URL("packages/cli/agents.en.json", root), "utf8"));
const out = fileURLToPath(new URL("apps/site/src/content/docs/en/extensions/agents.mdx", root));

// Same rules as packages/cli/src/ui/theme.ts stripEmoji and agents/catalog.ts.
const stripEmoji = (s) =>
  s
    .replace(/[\p{Extended_Pictographic}\u{1F1E6}-\u{1F1FF}\u200D\uFE0F\uFE0E\u20E3]/gu, "")
    .replace(/\s{2,}/g, " ")
    .trim();

function classifyAuth(auth) {
  if (/🆓|bepul|free/i.test(auth)) return "Free tier";
  if (auth.includes("💳")) return "Subscription";
  if (auth.includes("🌐")) return "Browser login";
  if (auth.includes("🔑")) return "API key";
  return "None";
}

function windows(install, win) {
  if (win === "-") return "WSL only";
  if (win) return "Yes";
  if (!install) return "Manual";
  if (/^bash\s/.test(install)) return "Needs Git Bash or WSL";
  if (/^brew\s/.test(install)) return "Manual";
  return "Yes";
}

// MDX table cell: escape pipes and characters MDX would parse.
const cell = (s) => s.replace(/\|/g, "\\|").replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);

const agents = [];
for (const raw of conf.split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith("#")) continue;
  const f = line.split("|").map((s) => s.trim());
  if (f.length < 6 || !f[0] || !f[1] || !f[2]) continue;
  const auth = stripEmoji(f[6] ?? "");
  const desc = stripEmoji(f[4] ?? "");
  const win = f.length > 8 ? f.slice(8).join(" | ").trim() : "";
  agents.push({
    name: f[0],
    command: f[2],
    category: f[5] ?? "",
    description: en[desc] ?? desc,
    login: classifyAuth(f[6] ?? ""),
    // "free tier — Google login" → "Google login" (the label already says free); no em-dashes.
    loginDetail: (en[auth] ?? auth)
      .replace(/^free( tier)? — /i, "")
      .replace(/\s*—\s*/g, ", "),
    url: f[7] ?? "",
    windows: windows(f[3] ?? "", win),
  });
}

const rows = agents.map((a) => {
  const name = a.url ? `[${cell(a.name)}](${a.url})` : cell(a.name);
  return `| ${name} | \`${cell(a.command)}\` | ${cell(a.category)} | **${a.login}**: ${cell(a.loginDetail)} | ${a.windows} |`;
});

const page = `---
title: "Agent catalog"
description: "All ${agents.length} AI CLI agents that atlas agents can install and launch."
sidebar:
  order: 2
---

{/* Generated by apps/site/scripts/gen-agents.mjs from packages/cli/agents.conf. Do not edit by hand. */}

${agents.length} agents. Open the picker with \`atlas agents\` (or \`/agents\` in chat), or launch one directly with \`atlas run <name>\`. See [AI agents launcher](/en/guides/agents/).

**Windows** column: **Yes** = installs natively (npm, pip, winget or PowerShell). **Needs Git Bash or WSL** = the installer is a bash script. **WSL only** = no native Windows build. **Manual** = install it yourself from the link.

| Agent | Command | Category | Login | Windows |
|---|---|---|---|---|
${rows.join("\n")}

Catalog derived from [Aidevix CLI](https://github.com/SunnatbekYusupovTech/sunnatbeeCLI) (MIT).
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, page, "utf8");
console.log(`wrote ${agents.length} agents → ${out}`);
