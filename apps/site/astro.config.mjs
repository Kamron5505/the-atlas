/**
 * Docs are written with root links (/guides/chat/). When the site is served from
 * a sub-path (GitHub Pages: /the-atlas/), prefix href/src attributes in the built HTML.
 */
function baseLinks() {
  return {
    name: "atlas-base-links",
    hooks: {
      "astro:build:done": async ({ dir }) => {
        if (!BASE) return;
        const { readdir, readFile, writeFile } = await import("node:fs/promises");
        const { join } = await import("node:path");
        const { fileURLToPath } = await import("node:url");
        const attr = new RegExp(`(\\s(?:href|src)=")(/(?!/)(?!${BASE.slice(1)}/)[^"]*)"`, "g");
        const walk = async (d) => {
          for (const e of await readdir(d, { withFileTypes: true })) {
            const p = join(d, e.name);
            if (e.isDirectory()) await walk(p);
            else if (p.endsWith(".html")) {
              const html = await readFile(p, "utf8");
              const out = html.replace(attr, (_, pre, url) => `${pre}${BASE}${url}"`);
              if (out !== html) await writeFile(p, out);
            }
          }
        };
        await walk(fileURLToPath(dir));
      },
    },
  };
}

